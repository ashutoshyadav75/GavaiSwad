
package com.softpro.GavaiSwad.Service;

import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

@Service
public class PdfReportService {

    public byte[] generateReport(
            long totalOrders,
            long pendingOrders,
            long deliveredOrders,
            BigDecimal totalRevenue,
            BigDecimal monthlySales
    ) throws IOException {

        try (PDDocument document = new PDDocument();
             ByteArrayOutputStream outputStream = new ByteArrayOutputStream()) {

            PDPage page = new PDPage(PDRectangle.A4);
            document.addPage(page);

            PDType1Font boldFont =
                    new PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD);

            PDType1Font regularFont =
                    new PDType1Font(Standard14Fonts.FontName.HELVETICA);

            try (PDPageContentStream content =
                         new PDPageContentStream(document, page)) {

                content.beginText();
                content.setFont(boldFont, 24);
                content.newLineAtOffset(180, 770);
                content.showText("GAVAI SWAD");
                content.endText();

                content.beginText();
                content.setFont(regularFont, 12);
                content.newLineAtOffset(190, 745);
                content.showText("ADMIN SALES REPORT");
                content.endText();

                content.moveTo(50, 725);
                content.lineTo(545, 725);
                content.stroke();

                String date = LocalDateTime.now().format(
                        DateTimeFormatter.ofPattern("dd-MM-yyyy HH:mm")
                );

                addLine(content, boldFont, 12,
                        "Generated On: " + date, 50, 690);

                addLine(content, boldFont, 16,
                        "ORDER SUMMARY", 50, 640);

                addLine(content, regularFont, 13,
                        "Total Orders: " + totalOrders, 70, 600);

                addLine(content, regularFont, 13,
                        "Pending Orders: " + pendingOrders, 70, 570);

                addLine(content, regularFont, 13,
                        "Delivered Orders: " + deliveredOrders, 70, 540);

                addLine(content, boldFont, 16,
                        "REVENUE SUMMARY", 50, 480);

                addLine(content, regularFont, 13,
                        "Total Revenue: Rs. " + totalRevenue, 70, 440);

                addLine(content, regularFont, 13,
                        "Current Month Sales: Rs. " + monthlySales, 70, 410);

                addLine(content, regularFont, 10,
                        "Generated by Gavai Swad Admin Panel", 150, 80);
            }

            document.save(outputStream);
            return outputStream.toByteArray();
        }
    }

    private void addLine(
            PDPageContentStream content,
            PDType1Font font,
            int fontSize,
            String text,
            float x,
            float y
    ) throws IOException {

        content.beginText();
        content.setFont(font, fontSize);
        content.newLineAtOffset(x, y);
        content.showText(text);
        content.endText();
    }
}
